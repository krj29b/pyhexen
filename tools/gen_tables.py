"""Generate src/pyhexen/core/tables_data.py from reference/src/tables.c and tables.h."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF_TABLES_C = ROOT / "reference" / "src" / "tables.c"
REF_TABLES_H = ROOT / "reference" / "src" / "tables.h"
OUT_PATH = ROOT / "src" / "pyhexen" / "core" / "tables_data.py"


def _extract_array(c_source: str, name: str, expected_len: int) -> list[int]:
    pattern = re.compile(
        rf"const\s+\w+\s+{re.escape(name)}\s*\[\s*\d+\s*\]\s*=\s*\{{([^}}]+)\}}\s*;",
        re.DOTALL,
    )
    match = pattern.search(c_source)
    if not match:
        raise ValueError(f"Could not find array {name!r} in tables.c")
    body = match.group(1)
    values = [int(tok.strip()) for tok in body.replace("\n", " ").split(",") if tok.strip()]
    if len(values) != expected_len:
        raise ValueError(f"Expected {expected_len} entries for {name}, got {len(values)}")
    return values


def _extract_define_int(h_source: str, name: str) -> int:
    pattern = re.compile(rf"^\s*#define\s+{re.escape(name)}\s+(\d+)\b", re.MULTILINE)
    match = pattern.search(h_source)
    if not match:
        raise ValueError(f"Could not find #define {name} in tables.h")
    return int(match.group(1))


def _format_tuple(name: str, values: list[int], per_line: int = 8) -> list[str]:
    lines = ["# fmt: off", f"{name}: tuple[int, ...] = ("]
    for i in range(0, len(values), per_line):
        chunk = ", ".join(str(v) for v in values[i : i + per_line])
        lines.append(f"    {chunk},")
    lines.extend([")", "# fmt: on"])
    return lines


def generate_tables(
    tables_c_path: Path = REF_TABLES_C,
    tables_h_path: Path = REF_TABLES_H,
    out_path: Path = OUT_PATH,
) -> None:
    """Parse reference tables.c/tables.h and write tables_data.py."""
    c_source = tables_c_path.read_text(encoding="utf-8")
    h_source = tables_h_path.read_text(encoding="utf-8")

    fineangles = _extract_define_int(h_source, "FINEANGLES")
    angletofineshift = _extract_define_int(h_source, "ANGLETOFINESHIFT")
    sloperange = _extract_define_int(h_source, "SLOPERANGE")
    slopebits = _extract_define_int(h_source, "SLOPEBITS")
    finemask = fineangles - 1
    dbits = 16 - slopebits

    finetangent = _extract_array(c_source, "finetangent", fineangles // 2)
    finesine = _extract_array(c_source, "finesine", 5 * fineangles // 4)
    tantoangle = [v & 0xFFFFFFFF for v in _extract_array(c_source, "tantoangle", sloperange + 1)]

    lines: list[str] = [
        "# PyHexen - Python reimplementation of the Hexen engine.",
        "# Portions derived from Hexen (c) Raven Software / id Software and Chocolate Doom,",
        "# released under the GNU GPL v2. This file is licensed GPL-2.0-or-later.",
        "",
        '"""Lookup tables generated by tools/gen_tables.py from reference/src/tables.c."""',
        "",
        "from __future__ import annotations",
        "",
        f"FINEANGLES: int = {fineangles}",
        f"FINEMASK: int = {finemask}",
        f"ANGLETOFINESHIFT: int = {angletofineshift}",
        f"SLOPERANGE: int = {sloperange}",
        f"SLOPEBITS: int = {slopebits}",
        f"DBITS: int = {dbits}",
        "",
    ]
    lines.extend(_format_tuple("FINETANGENT", finetangent))
    lines.append("")
    lines.extend(_format_tuple("FINESINE", finesine))
    lines.append("")
    lines.append(f"FINECOSINE: tuple[int, ...] = FINESINE[{fineangles // 4}:{5 * fineangles // 4}]")
    lines.append("")
    lines.extend(_format_tuple("TANTOANGLE", tantoangle))
    lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    generate_tables()
